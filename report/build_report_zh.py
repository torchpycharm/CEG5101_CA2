h2('4.2  避免误封受害主机')
body('**问题。** ICMP 洪泛会让受害主机回应每一个请求，所以受害主机会以与洪泛相同的速率把 Echo Reply 发回'
     '攻击者。按源地址统计所有 IPv4 包的检测器因此会看到两个"异常"源：攻击者和受害者。我们控制器的第一版'
     '正是如此，在场景 a 中把 h3 和 h2 一起封了。在场景 b 和 c 中受害者是 h6，也就是合法流的目的主机。封禁'
     ' h6 会丢弃 h6 发出的所有包，包括 h1→h6 会话的 ping 回复和 iperf3 控制流量，等于切断了检测器本该保护'
     '的流量。')
body('**第一次尝试。** 第二版仍为每个源保留一个计数器，并在每一轮统计中，用该主机收到的 Echo Request 去'
     '抵扣它发出的 Echo Reply。这样仍会时常误封受害者。各交换机的 OpenFlow 统计回复是异步到达的，一个请求'
     '和它的回复常常被计入不同的轮次（攻击者被封之后，剩余的回复也没有请求可以抵扣），所以同轮抵扣并不可靠。')
