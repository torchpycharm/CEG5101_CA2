         '攻击，或每个源都低于下限的分布式攻击，都不会被检测到。检测按源 IP 进行，伪造源地址的攻击者可以绕过'
         ' IP 封禁；按接入端口封禁会更稳健。',
         '**排除 Echo Reply 的适用范围。** 排除回复避免了误封受害者，但只由 Echo Reply 组成的洪泛（如反射'
